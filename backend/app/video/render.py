"""FFmpeg render engine: per-scene animated clips -> concat -> narration + ducked music
-> burned-in subtitles -> loudness-normalized MP4 (1920x1080 or 1080x1920)."""
from __future__ import annotations

import logging
import random
import shutil
from pathlib import Path
from typing import Any

from ..config import get_settings
from ..util import ffprobe_duration, run

log = logging.getLogger(__name__)
FPS = 30
SIZES = {"long": (1920, 1080), "short": (1080, 1920)}
MOVES = ["in", "out", "left", "right", "up", "in"]


def _zoompan(move: str, n: int) -> str:
    if move == "in":
        return f"z='1+0.13*on/{n}':x='iw/2-(iw/zoom/2)':y='ih/2-(ih/zoom/2)'"
    if move == "out":
        return f"z='1.13-0.13*on/{n}':x='iw/2-(iw/zoom/2)':y='ih/2-(ih/zoom/2)'"
    if move == "left":
        return f"z=1.12:x='(iw-iw/zoom)*(1-on/{n})':y='ih/2-(ih/zoom/2)'"
    if move == "right":
        return f"z=1.12:x='(iw-iw/zoom)*on/{n}':y='ih/2-(ih/zoom/2)'"
    return f"z=1.12:x='iw/2-(iw/zoom/2)':y='(ih-ih/zoom)*(1-on/{n})'"


def scene_clip(image: Path, duration: float, out: Path, size: tuple[int, int], move: str,
               text: str = "", fast: bool = False) -> None:
    W, H = size
    n = max(1, int(round(duration * FPS)))
    W2, H2 = W * 2, H * 2
    fade = min(0.45, duration / 4)
    vf = [f"scale={W2}:{H2}:force_original_aspect_ratio=increase", f"crop={W2}:{H2}", "setsar=1",
          f"zoompan={_zoompan(move, n)}:d={n}:s={W}x{H}:fps={FPS}",
          "eq=contrast=1.08:saturation=0.8:brightness=-0.02", "vignette=PI/4.2",
          "noise=alls=3:allf=t"]
    if text:
        tf = out.with_suffix(".txt")
        tf.write_text(text.upper()[:60])
        hold = max(0.2, duration - 0.6)
        fs = int(H * (0.045 if W > H else 0.032))
        y = f"h-{int(H * 0.2)}" if W > H else f"{int(H * 0.12)}"
        vf.append(f"drawtext=fontfile=/usr/share/fonts/truetype/dejavu/DejaVuSerif-Bold.ttf:textfile='{tf.name}':"
                  f"fontsize={fs}:fontcolor=white@0.92:x={int(W * 0.06)}:y={y}:box=1:boxcolor=black@0.45:"
                  f"boxborderw=18:alpha='if(lt(t,{min(0.6, duration / 4):.2f}),t/{min(0.6, duration / 4):.2f},if(lt(t,{min(3.6, hold):.2f}),1,max(0,1-(t-{min(3.6, hold):.2f})/0.6)))'")
    vf += [f"fade=t=in:st=0:d={fade:.2f}", f"fade=t=out:st={duration - fade:.2f}:d={fade:.2f}",
           "format=yuv420p"]
    run(["ffmpeg", "-y", "-loglevel", "error", "-i", image, "-vf", ",".join(vf), "-frames:v", n,
         "-r", FPS, "-c:v", "libx264", "-preset", "ultrafast" if fast else "veryfast", "-crf", "20",
         "-an", out.name], cwd=out.parent)


def ambient_music(duration: float, out: Path, seed: int = 0) -> dict:
    """Use a licensed track from MUSIC_DIR if present, else synthesize an original drone."""
    mdir = get_settings().music_dir
    tracks = sorted([*mdir.glob("*.mp3"), *mdir.glob("*.wav")]) if mdir.exists() else []
    if tracks:
        t = tracks[seed % len(tracks)]
        run(["ffmpeg", "-y", "-loglevel", "error", "-stream_loop", "-1", "-i", t, "-t", f"{duration:.2f}",
             "-af", f"afade=t=in:d=3,afade=t=out:st={max(0, duration - 4):.2f}:d=4", "-ar", "44100", out])
        return {"music": t.name, "license": "user-supplied (see data/music/LICENSES.txt)"}
    r = random.Random(seed)
    root = r.choice([49.0, 55.0, 58.27, 65.41])
    expr = "+".join(f"{a}*sin(2*PI*{root * m}*t)*(0.55+0.45*sin(2*PI*{lfo}*t+{ph}))"
                    for a, m, lfo, ph in [(0.10, 1, 0.031, 0), (0.06, 1.5, 0.047, 1.3), (0.045, 2, 0.023, 2.1),
                                          (0.03, 3, 0.061, 0.7), (0.02, 4.0, 0.017, 2.9)])
    run(["ffmpeg", "-y", "-loglevel", "error", "-f", "lavfi", "-i",
         f"aevalsrc='{expr}':s=44100:d={duration:.2f}", "-f", "lavfi", "-i",
         f"anoisesrc=color=brown:amplitude=0.05:d={duration:.2f}:r=44100",
         "-filter_complex", "[1]lowpass=f=300[n];[0][n]amix=inputs=2:normalize=0,"
                            f"aecho=0.8:0.7:600:0.3,afade=t=in:d=4,afade=t=out:st={max(0, duration - 5):.2f}:d=5",
         "-ac", "2", out])
    return {"music": "procedural ambient drone", "license": "Generated by this app (no third-party rights)"}


# ---------------------------------------------------------------- subtitles
def _chunks(words: list, short: bool) -> list[tuple[float, float, str]]:
    out, cur = [], []
    max_w, max_c = (3, 18) if short else (7, 42)
    for w in words:
        cur.append(w)
        text = " ".join(x[2] for x in cur)
        if len(cur) >= max_w or len(text) >= max_c or w[2][-1:] in ".?!,;:":
            out.append((cur[0][0], cur[-1][1], text))
            cur = []
    if cur:
        out.append((cur[0][0], cur[-1][1], " ".join(x[2] for x in cur)))
    # close tiny gaps so subtitles don't flicker
    return [(s, max(e, out[i + 1][0] if i + 1 < len(out) and out[i + 1][0] - e < 0.4 else e), t)
            for i, (s, e, t) in enumerate(out)]


def _ass_time(t: float) -> str:
    cs = int(round(max(0.0, t) * 100))
    return f"{cs // 360000}:{cs // 6000 % 60:02d}:{cs // 100 % 60:02d}.{cs % 100:02d}"


def _srt_time(t: float) -> str:
    ms = int(round(max(0.0, t) * 1000))
    return f"{ms // 3600000:02d}:{ms // 60000 % 60:02d}:{ms // 1000 % 60:02d},{ms % 1000:03d}"


def _ass_escape(s: str) -> str:
    return s.replace("\\", "").replace("{", "(").replace("}", ")").replace("\n", " ")


def write_subtitles(words: list, out_dir: Path, fmt: str) -> tuple[Path, Path]:
    short = fmt == "short"
    W, H = SIZES[fmt]
    chunks = _chunks(words, short)
    style = ("Style: Default,DejaVu Sans,96,&H00FFFFFF,&H0000E5FF,&H00000000,&H64000000,-1,0,0,0,100,100,0,0,1,7,2,5,60,60,0,1"
             if short else
             "Style: Default,DejaVu Sans,52,&H00FFFFFF,&H000000FF,&H00101010,&H80000000,-1,0,0,0,100,100,0,0,1,3.2,1.5,2,160,160,64,1")
    lines = ["[Script Info]", "ScriptType: v4.00+", f"PlayResX: {W}", f"PlayResY: {H}", "WrapStyle: 0", "",
             "[V4+ Styles]",
             "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, "
             "Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, "
             "Alignment, MarginL, MarginR, MarginV, Encoding", style, "", "[Events]",
             "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text"]
    for s, e, t in chunks:
        t = _ass_escape(t)
        txt = t.upper() if short else t
        if short:  # pop-in animation, yellow emphasis on long words
            txt = "{\\fscx80\\fscy80\\t(0,90,\\fscx100\\fscy100)}" + " ".join(
                "{\\c&H00E5FF&}" + w + "{\\c&HFFFFFF&}" if len(w) > 6 else w for w in txt.split())
        lines.append(f"Dialogue: 0,{_ass_time(s)},{_ass_time(e)},Default,,0,0,0,,{txt}")
    ass = out_dir / "subtitles.ass"
    ass.write_text("\n".join(lines))
    srt = out_dir / "subtitles.srt"
    srt.write_text("".join(f"{i}\n{_srt_time(s)} --> {_srt_time(e)}\n{t}\n\n"
                           for i, (s, e, t) in enumerate(_chunks(words, False), 1)))
    return ass, srt


# ---------------------------------------------------------------- full render
def render(scenes: list[dict], audio: dict, visuals: dict[int, str], out_dir: Path, fmt: str = "long",
           fast: bool = False, seed: int = 0) -> dict[str, Any]:
    size = SIZES[fmt]
    clips_dir = out_dir / f"clips_{fmt}"
    shutil.rmtree(clips_dir, ignore_errors=True)
    clips_dir.mkdir(parents=True)
    seg_by_scene = {s["scene_id"]: s for s in audio["segments"]}
    clip_files = []
    for i, sc in enumerate(scenes):
        seg = seg_by_scene[sc["id"]]
        clip = clips_dir / f"clip_{i:03d}.mp4"
        scene_clip(Path(visuals[sc["id"]]), seg["duration"], clip, size, MOVES[(i + seed) % len(MOVES)],
                   sc.get("on_screen_text", ""), fast)
        clip_files.append(clip)
    lst = clips_dir / "list.txt"
    lst.write_text("".join(f"file '{c.name}'\n" for c in clip_files))
    silent = out_dir / f"video_{fmt}_silent.mp4"
    run(["ffmpeg", "-y", "-loglevel", "error", "-f", "concat", "-safe", "0", "-i", lst, "-c", "copy", silent])
    dur = audio["duration"]
    music = out_dir / f"music_{fmt}.wav"
    music_info = ambient_music(dur, music, seed)
    ass, srt = write_subtitles(audio["words"], out_dir, fmt)
    final = out_dir / f"final_{fmt}.mp4"
    mvol = 0.22 if fmt == "long" else 0.3
    fc = (f"[1:a]aresample=44100,asplit=2[n1][n2];[2:a]aresample=44100,volume={mvol}[m];"
          "[m][n1]sidechaincompress=threshold=0.04:ratio=6:attack=30:release=500[duck];"
          "[n2][duck]amix=inputs=2:duration=first:normalize=0,loudnorm=I=-14:TP=-1.5:LRA=11[a];"
          f"[0:v]subtitles={ass.name}[v]")
    run(["ffmpeg", "-y", "-loglevel", "error", "-i", silent, "-i", audio["path"], "-i", music,
         "-filter_complex", fc, "-map", "[v]", "-map", "[a]", "-c:v", "libx264",
         "-preset", "veryfast" if fast else "medium", "-crf", "21", "-maxrate", "12M", "-bufsize", "24M",
         "-pix_fmt", "yuv420p",
         "-c:a", "aac", "-b:a", "192k", "-ar", "48000", "-movflags", "+faststart", "-shortest", final],
        cwd=out_dir)
    shutil.rmtree(clips_dir, ignore_errors=True)
    silent.unlink(missing_ok=True)
    return {"path": str(final), "duration": round(ffprobe_duration(final), 2), "size": f"{size[0]}x{size[1]}",
            "subtitles_srt": str(srt), "subtitles_ass": str(ass), **music_info}
